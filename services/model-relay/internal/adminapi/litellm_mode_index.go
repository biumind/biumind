// lookupLiteLLMMode 按 model_name 在 LiteLLM 字典中查 mode.
// 命中规则 (按优先级):
//   1. exact match: code 完全匹配 (e.g. 'gpt-4o-mini-tts')
//   2. strip prefix: 含 '/' 时取尾部 (e.g. 'openai/dall-e-3' → 'dall-e-3')
// 不命中返回 "" — 调用方应继续启发式或落到默认.
func lookupLiteLLMMode(code string) string {
	if m, ok := litellmModeIndex[code]; ok {
		return m
	}
	if idx := strings.LastIndex(code, "/"); idx > 0 && idx < len(code)-1 {
		if m, ok := litellmModeIndex[code[idx+1:]]; ok {
			return m
		}
	}
	return ""
}
